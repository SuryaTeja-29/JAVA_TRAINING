package DAY2;

public class RelationalOperators {
    public static void main(){
        int a = 5,b=7;
        System.out.println(a > b);//F
        System.out.println(a < b);//T
        System.out.println(a >= b);//F
        System.out.println(a <= b);//T
        System.out.println(a == b);//F
        System.out.println(a != b);//T
    }
}
